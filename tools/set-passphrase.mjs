#!/usr/bin/env node
/*
 * Derive the owner passphrase hash that ships with the site.
 *
 *   node tools/set-passphrase.mjs "your new passphrase"
 *   node tools/set-passphrase.mjs            # reads BLOG_OWNER_PASSPHRASE from .env
 *
 * Writes assets/auth.js (committed, ships to the browser) holding only a random
 * salt and a PBKDF2-SHA256 digest. The plaintext stays in .env, which is
 * gitignored and never leaves this machine.
 *
 * The digest is public by necessity — a static site has no server to check a
 * password on, so whatever the browser compares against is readable by anyone
 * who views source. Hashing keeps the plaintext out of the repo; it does not
 * make the gate secure. See README for what that does and doesn't buy you.
 */
import { pbkdf2Sync, randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ITERATIONS = 210000;
const KEY_LEN = 32;

function fromEnvFile() {
  const envPath = join(ROOT, '.env');
  if (!existsSync(envPath)) return null;
  for (const line of readFileSync(envPath, 'utf8').split('\n')) {
    const m = line.match(/^\s*BLOG_OWNER_PASSPHRASE\s*=\s*(.*)\s*$/);
    if (m) return m[1].replace(/^["']|["']$/g, '');
  }
  return null;
}

const passphrase = process.argv[2] || fromEnvFile();

if (!passphrase) {
  console.error('No passphrase given.\n');
  console.error('  node tools/set-passphrase.mjs "your new passphrase"');
  console.error('  or put BLOG_OWNER_PASSPHRASE=... in .env and run with no arguments');
  process.exit(1);
}
if (passphrase.length < 12) {
  console.error(`Passphrase is ${passphrase.length} characters. Use at least 12 —`);
  console.error('the digest ships publicly, so a short one is brute-forceable offline.');
  process.exit(1);
}

const salt = randomBytes(16);
const hash = pbkdf2Sync(passphrase, salt, ITERATIONS, KEY_LEN, 'sha256');

const out = `/* Generated by tools/set-passphrase.mjs — do not edit by hand.
   Salt + PBKDF2-SHA256 digest of the owner passphrase. The plaintext lives in
   .env (gitignored). This file is public: it only gates the authoring UI. */
window.BLOG_AUTH = {
  v: 1,
  algorithm: 'PBKDF2-SHA256',
  iterations: ${ITERATIONS},
  salt: '${salt.toString('hex')}',
  hash: '${hash.toString('hex')}'
};
`;

writeFileSync(join(ROOT, 'assets', 'auth.js'), out);
console.log('Wrote assets/auth.js');
console.log(`  PBKDF2-SHA256, ${ITERATIONS} iterations, 16-byte salt`);
console.log('\nNext: git add -A && git commit -m "rotate owner passphrase" && git push');
